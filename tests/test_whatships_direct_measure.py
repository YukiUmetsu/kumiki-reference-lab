class DirectWhatshipsNumericMeasurementTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.home=Path(self.temp.name)
        self.catalog=self.home/"catalog.json"
        self.catalog.write_text(json.dumps(whatships_fixture()))
        self.media=self.home/"local-video.mp4"
        self.media.write_bytes(b"authorized simulated motion clip; no actual media decoder here")
        self.sha=hashlib.sha256(self.media.read_bytes()).hexdigest()
        self.ledger=self.home/"private-bindings.json"
        self.ledger.write_text(json.dumps({
            "schemaVersion":"kumiki.whatships-local-media-bindings.v1",
            "createdOn":"2026-11-11",
            "catalogIndexUrl":"https://whatships.com/search-index.json",
            "disclaimer":"self-declared-source-identity-and-authorization-only",
            "bindings":[{
                "sourceId":"whatships:film-one",
                "watchUrl":"https://whatships.com/videos/film-one/",
                "localPath":str(self.media.resolve()),
                "mediaSha256":self.sha,
                "mediaSizeBytes":self.media.stat().st_size,
                "sourceStreamIndex":0,
                "sourceTimebase":{"numerator":1,"denominator":1000},
                "rightsBasis":"own-original-work",
                "rightsNote":"The fixture video is generated by the operator for local analysis.",
                "identityNote":"This local video is a test-only exact source binding for film-one.",
                "rightsStatus":"user-declared-authorized",
                "verificationStatus":"operator-attestation-not-independently-verified",
                "boundOn":"2026-11-11",
            }],
        }))
        self.repository=self.home/"research/analysis/whatships"
        self.repository.parent.mkdir(parents=True)
        note=self.home/"observed.json"
        note.write_text(json.dumps({
            "schemaVersion":"kumiki.browser-video-observations.v1",
            "reviewedOn":"2026-11-11",
            "methodology":"selected moments only",
            "observations":[{
                "sourceId":"whatships:film-one","reviewedOn":"2026-11-11",
                "method":"browser-player","coverage":"selected-moments-only",
                "visualTags":["paper-cut"],"visibleMoments":["A layered card folds."],
                "techniqueHypotheses":["Layered motion is plausible."],
            }],
        }))
        export_repository_analysis(self.catalog,self.repository,observations_path=note)
        self.samples=[]
        self.fail_second=False
        self.leak_extra_field=False
        self.wrong_report_sha=False
        self.inspected_timebase={"numerator":1,"denominator":1000}

    def mock_inspect(self, path, *, ffprobe, rights_status):
        self.assertEqual(path,self.media)
        self.assertEqual(rights_status,"user-declared-authorized")
        return {
            "source":{"sha256":self.sha},
            "video":{
                "streamIndex":0,
                "sourceTimebase":self.inspected_timebase,
                "durationSecondsReported":"8.0",
            },
        }

    def mock_probe(self, path, *, start_seconds, seconds, max_samples,
                   width, height, cut_threshold, rights_status, ffmpeg, ffprobe):
        self.assertEqual(path,self.media)
        self.samples.append((start_seconds,seconds,max_samples))
        if self.fail_second and start_seconds > 0:
            raise ValueError("simulated second-window source decoder failure")
        positions=[start_seconds*1000+offset for offset in (0,500,1000,1500,2000)]
        def frame(pos):
            datum={
                "sourcePts":pos,
                "sourceSeconds":{"numerator":pos,"denominator":1000},
                "appearance":{
                    "meanRgb":[.2,.4,.3],"meanDisplayLumaProxy":.3,
                    "displayLumaStdDev":.1,"meanSaturationProxy":.5,
                    "shadowPixelFraction":.08,"brightPixelFraction":.07,
                },
            }
            if self.leak_extra_field:
                datum["localFilePath"]="/Users/private/home-video.mp4"
            return datum
        return {
            "schemaVersion":"kumiki.source-pts-visual-probe.v1",
            "sourceSha256":("f"*64 if self.wrong_report_sha else self.sha),
            "sourceStreamIndex":0,
            "sourceTimebase":{"numerator":1,"denominator":1000},
            "scan":{
                "startSeconds":start_seconds,"requestedSeconds":seconds,
                "sourceWindowEndSeconds":start_seconds+seconds,
                "sourceTimebaseVerified":True,
                "sampledSourcePtsCount":5,
                "sourcePtsFramesSeenInInventory":15,
                "decoder":"source-prefix-ordinal-pts-v1",
                "cutThreshold":cut_threshold,
                "frameWidth":width,"frameHeight":height,
            },
            "cutCandidatePts":[],
            "sampledFrames":[frame(x) for x in positions],
            "sampledFramePairs":[{
                "startPts":positions[i-1],"endPts":positions[i],
                "sourceDeltaSeconds":{"numerator":1,"denominator":2},
                "status":"rgb-image-difference-proxy",
                "meanAbsoluteDisplayRgbDelta":.02,
                "meanAbsoluteDisplayRgbDeltaPerSecond":.04,
            } for i in range(1,len(positions))],
            "sampledWindowSummary":{
                "cutCandidateCountBetweenFirstAndLastSample":0,
                "cutCandidateRatePerRequestedMinute":0.0,
                "meanSampledDisplayLumaProxy":.3,
                "meanSampledSaturationProxy":.5,
                "meanWithinShotDisplayRgbDelta":.02,
                "withinShotComparedPairs":4,"cutSeparatedPairs":0,
            },
            "evidenceStatus":"original-source-pts-sampled-numeric-proxies-not-human-reviewed",
        }

    def run_mock(self, **changes):
        with (
            patch("kumiki_reference_lab.catalog.whatships_direct_measure.inspect_source",
                  side_effect=self.mock_inspect),
            patch("kumiki_reference_lab.catalog.whatships_direct_measure.analyze_source_visual_window",
                  side_effect=self.mock_probe),
        ):
            return measure_whatships_to_repository(
                self.catalog,self.ledger,"whatships:film-one",self.repository,
                **{"window_seconds":3,"window_count":2,"max_samples":5,**changes})

    def test_measures_two_windows_and_merges_earlier_browser_evidence(self):
        result=self.run_mock()
        self.assertTrue(result["gitWorkingTreeUpdated"])
        self.assertEqual(result["sampledOriginalSourceFrames"],10)
        self.assertEqual(result["framesInWindowPtsInventories"],30)
        self.assertEqual(result["sampledFrameFractionOfScannedWindowInventories"],
                         round(10/30,6))
        self.assertEqual(result["requestedWindowTimeFractionOfReportedFilmDuration"],.75)
        self.assertEqual(result["measuredOriginalSourceWindows"],2)
        self.assertEqual(self.samples,[(0,3,5),(5,3,5)])
        self.assertFalse(result["fullFilmReviewed"])
        record=json.loads((self.repository/"film-one.json").read_text())
        self.assertIn("browserSpotCheck",record["evidence"])
        self.assertIn("numericVisual",record["evidence"])
        self.assertFalse(record["coverage"]["fullFilmReviewed"])
        windows=record["evidence"]["numericVisual"]["windows"]
        self.assertEqual([w["startSeconds"] for w in windows],[0,5])
        self.assertEqual(windows[1]["sampledFrames"][1]["sourcePts"],5500)
        self.assertNotIn(str(self.home),(self.repository/"film-one.json").read_text())
        self.assertEqual(validate_repository_analysis(self.repository,self.catalog)
                         ["numericSampledVideos"],1)

    def test_unmodified_second_run_does_not_duplicate_data(self):
        self.run_mock()
        before=(self.repository/"film-one.json").read_bytes()
        next_result=self.run_mock()
        self.assertFalse(next_result["gitWorkingTreeUpdated"])
        self.assertEqual((self.repository/"film-one.json").read_bytes(),before)

    def test_failure_after_one_decoded_window_does_not_change_git(self):
        self.fail_second=True
        before=(self.repository/"film-one.json").read_bytes()
        index_before=(self.repository/"index.json").read_bytes()
        with self.assertRaisesRegex(ValueError,"second-window"):
            self.run_mock()
        self.assertEqual((self.repository/"film-one.json").read_bytes(),before)
        self.assertEqual((self.repository/"index.json").read_bytes(),index_before)

    def test_numeric_evidence_cannot_leak_private_frame_path(self):
        self.leak_extra_field=True
        with self.assertRaisesRegex(ValueError,"schema changed|source PTS|approved"):
            self.run_mock()
        self.assertNotIn("numericVisual",json.loads(
            (self.repository/"film-one.json").read_text())["evidence"])

    def test_mismatched_source_sha_fails_before_git_mutation(self):
        self.wrong_report_sha=True
        with self.assertRaisesRegex(ValueError,"wrong media provenance"):
            self.run_mock()
        self.assertNotIn("numericVisual",json.loads(
            (self.repository/"film-one.json").read_text())["evidence"])

    def test_replaced_media_refuses_before_model_or_probe(self):
        self.media.write_bytes(b"modified local source video after rights binding")
        with self.assertRaisesRegex(ValueError,"fingerprint differs"):
            self.run_mock()
        self.assertEqual(self.samples,[])

    def test_mismatched_stream_timebase_fails_before_decode(self):
        self.inspected_timebase={"numerator":1,"denominator":30000}
        with self.assertRaisesRegex(ValueError,"stream or timebase changed"):
            self.run_mock()
        self.assertEqual(self.samples,[])

    def test_conflicting_numeric_requires_explicit_replace(self):
        self.run_mock()
        self.samples.clear()
        before=(self.repository/"film-one.json").read_bytes()
        # Deliberately change one measured numeric field while preserving schema.
        old=self.mock_probe
        def modified(*args,**kwargs):
            result=old(*args,**kwargs)
            result["sampledFrames"][0]["appearance"]["meanSaturationProxy"]=.6
            return result
        with (
            patch("kumiki_reference_lab.catalog.whatships_direct_measure.inspect_source",
                  side_effect=self.mock_inspect),
            patch("kumiki_reference_lab.catalog.whatships_direct_measure.analyze_source_visual_window",
                  side_effect=modified),
        ):
            with self.assertRaisesRegex(ValueError,"replace-existing"):
                measure_whatships_to_repository(
                    self.catalog,self.ledger,"whatships:film-one",self.repository,
                    window_seconds=3,window_count=2,max_samples=5)
        self.assertEqual((self.repository/"film-one.json").read_bytes(),before)

    def test_invalid_bounds_rejected_without_decoding(self):
        for args in ({"window_count":7},{"window_seconds":0},
                     {"max_samples":1},{"width":1000},
                     {"cut_threshold":float("nan")},{"replace_existing":None}):
            with self.subTest(args=args),self.assertRaises(ValueError):
                self.run_mock(**args)
        self.assertEqual(self.samples,[])

    def test_cli_one_command_commits_derived_data_to_worktree(self):
        capture=io.StringIO()
        with (
            patch("kumiki_reference_lab.catalog.whatships_direct_measure.inspect_source",
                  side_effect=self.mock_inspect),
            patch("kumiki_reference_lab.catalog.whatships_direct_measure.analyze_source_visual_window",
                  side_effect=self.mock_probe),
            contextlib.redirect_stdout(capture),
        ):
            code=main([
                "whatships-measure",str(self.ledger),"whatships:film-one",
                "--snapshot",str(self.catalog),
                "--repository-root",str(self.repository),
                "--window-seconds","3","--window-count","2","--max-samples","5",
            ])
        self.assertEqual(code,0)
        report=json.loads(capture.getvalue())
        self.assertEqual(report["measuredOriginalSourceWindows"],2)
        self.assertNotIn(str(self.home),capture.getvalue())


class DirectWindowPlannerTests(unittest.TestCase):
    def test_nonoverlapping_endpoints_and_reported_duration(self):
        self.assertEqual(_duration_windows("8.0",window_seconds=3,window_count=2),
                         ([(0,3),(5,8)],.75))
        self.assertEqual(_duration_windows("2.9",window_seconds=10,window_count=4),
                         ([(0,2)],round(2/2.9,6)))
        for bad in ("0.5","0",None,"NaN","infinity","-6","bad"):
            with self.subTest(duration=bad),self.assertRaises(ValueError):
                _duration_windows(bad,window_seconds=3,window_count=2)


if __name__=="__main__":
    unittest.main()
